"""
Build a larger, decontaminated held-out corpus for tokenizer evaluation.

This script is intentionally separate from ``build_tokenizer_corpus.py``.
It reuses that builder's normalization, chunking, deterministic sampling, and
provenance structures, then adds evaluation-specific protections:

1. Evaluation sources must be supplied separately from tokenizer-training sources.
2. A frozen training corpus is REQUIRED via --training-corpus.
3. Candidate documents are rejected if they come from the same original source
   document used by training (when provenance is available).
4. Exact normalized text matches against training are rejected.
5. Optional deterministic word-shingle overlap checks reject likely excerpts /
   near-duplicates of training text.
6. Per-source-document byte caps reduce domination by a single long source.

Recommended layout
------------------
data/
    tokenizer_training/
        v0.2/
            tokenizer_corpus.jsonl
    tokenizer_eval_sources/
        general/
        logical/
        mathematics/
        science/
        engineering/
        software/
        code/
        networking/
        business_finance/
        humanities/
        structured_mixed/
    evaluation/
        tokenizer_eval.txt          # original benchmark: NEVER modify
        v0.2/                       # generated by this script
            tokenizer_eval.jsonl
            manifest.json
            build_report.json

The default v0.2 evaluation mixture is:
    general             25%
    logical             12%
    mathematics         12%
    science             10%
    engineering         10%
    software             8%
    code                 7%
    networking           5%
    business_finance     4%
    humanities           5%
    structured_mixed     2%

The default target is 500,000 UTF-8 bytes.

PowerShell example
------------------
python scripts/build_tokenizer_eval_corpus.py `
    --source general=data\\tokenizer_eval_sources\\general `
    --source logical=data\\tokenizer_eval_sources\\logical `
    --source mathematics=data\\tokenizer_eval_sources\\mathematics `
    --source science=data\\tokenizer_eval_sources\\science `
    --source engineering=data\\tokenizer_eval_sources\\engineering `
    --source software=data\\tokenizer_eval_sources\\software `
    --source code=data\\tokenizer_eval_sources\\code `
    --source networking=data\\tokenizer_eval_sources\\networking `
    --source business_finance=data\\tokenizer_eval_sources\\business_finance `
    --source humanities=data\\tokenizer_eval_sources\\humanities `
    --source structured_mixed=data\\tokenizer_eval_sources\\structured_mixed `
    --training-corpus data\\tokenizer_training\\v0.2\\tokenizer_corpus.jsonl `
    --target-bytes 500000 `
    --output data\\evaluation\\v0.2

Important
---------
This is a decontamination safety layer, not a substitute for source provenance.
The strongest policy is still: evaluation documents must come from genuinely
different source documents than tokenizer training.
"""

