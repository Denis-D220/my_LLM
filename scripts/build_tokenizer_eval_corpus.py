def validate_args(args: argparse.Namespace) -> None:
    if not args.text_field:
        raise ValueError("--text-field cannot be empty")
    if args.max_chars < args.min_chars:
        raise ValueError("--max-chars must be >= --min-chars")
    if args.chunk_target_chars > args.max_chars:
        raise ValueError("--chunk-target-chars must be <= --max-chars")
    if args.min_tail_chars > args.max_chars:
        raise ValueError("--min-tail-chars must be <= --max-chars")

    categories = [spec.category for spec in args.source]
    duplicates = sorted(
        category for category, count in Counter(categories).items() if count > 1
    )
    if duplicates:
        raise ValueError(
            "each evaluation category may appear only once in --source; duplicates: "
            + ", ".join(duplicates)
        )

    weighted_categories = [category for category, _ in args.weight]
    duplicate_weights = sorted(
        category
        for category, count in Counter(weighted_categories).items()
        if count > 1
    )
    if duplicate_weights:
        raise ValueError(
            "each category may appear only once in --weight; duplicates: "
            + ", ".join(duplicate_weights)
        )

    unknown_weights = sorted(set(weighted_categories) - set(categories))
    if unknown_weights:
        raise ValueError(
            "--weight supplied for category without matching --source: "
            + ", ".join(unknown_weights)
        )

    training = args.training_corpus.expanduser().resolve()
    if not training.is_file():
        raise FileNotFoundError(f"training corpus does not exist: {training}")


def resolve_weights(
    sources: Sequence[base.SourceSpec],
    overrides: Sequence[tuple[str, float]],
) -> dict[str, float]:
    override_map = dict(overrides)
    raw: dict[str, float] = {}

    for source in sources:
        if source.category in override_map:
            weight = override_map[source.category]
        else:
            weight = DEFAULT_CATEGORY_WEIGHTS.get(source.category, 1.0)
        raw[source.category] = weight

    total = sum(raw.values())
    if total <= 0:
        raise ValueError("at least one evaluation category must have positive weight")

    return {category: value / total for category, value in raw.items()}


def canonical_source_document_key(
    source_file: str,
    source_record: int | None,
) -> tuple[str, int | None]:
    """Canonicalize source provenance for same-source-document exclusion."""
    path = Path(source_file).expanduser()
    try:
        canonical = str(path.resolve())
    except OSError:
        canonical = str(path)
    return canonical.casefold(), source_record


def stable_ngram_hash(words: Sequence[str]) -> int:
    payload = "\x1f".join(words).encode("utf-8", errors="strict")
    digest = hashlib.blake2b(payload, digest_size=8).digest()
    return int.from_bytes(digest, "big", signed=False)


def word_ngram_hashes(text: str, n: int) -> list[int]:
    """Return deterministic n-gram hashes, preserving repeated shingles."""
    words = _WORD_RE.findall(text)
    if len(words) < n:
        return []

    return [
        stable_ngram_hash(words[index : index + n])
        for index in range(len(words) - n + 1)
    ]


def unique_word_ngram_hashes(text: str, n: int) -> set[int]:
    """Return unique deterministic n-gram hashes for the training index."""
    return set(word_ngram_hashes(text, n))


def load_training_reference(
    path: Path,
    *,
    text_field: str,
    ngram_size: int,
    build_ngrams: bool,
) -> TrainingReference:
    """Load exact-text, provenance, and optional n-gram fingerprints from training."""
    source_keys: set[tuple[str, int | None]] = set()
    text_hashes: set[str] = set()
    ngram_hashes: set[int] = set()
    documents = 0
    utf8_bytes = 0

    with path.open("r", encoding="utf-8", errors="strict", newline="") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue

            try:
                record = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(
                    f"invalid training-corpus JSON at line {line_number}: {exc.msg}"
                ) from exc

            if not isinstance(record, dict):
                raise ValueError(
                    f"training corpus line {line_number} must be a JSON object"
                )

            text = record.get(text_field)
            if not isinstance(text, str):
                raise ValueError(
                    f"training corpus line {line_number} missing string field "
                    f"{text_field!r}"
                )

            normalized = base.normalize_text(text)
            encoded = normalized.encode("utf-8", errors="strict")
            digest = hashlib.sha256(encoded).hexdigest()

            documents += 1
            utf8_bytes += len(encoded)
            text_hashes.add(digest)

            source_file = record.get("source_file")
            source_record = record.get("source_record")
            if source_file is not None and not isinstance(source_file, str):
                raise ValueError(
                    f"training corpus line {line_number}: source_file must be string/null"
                )
            if source_record is not None and not isinstance(source_record, int):
                raise ValueError(
                    f"training corpus line {line_number}: source_record must be int/null"
                )

            if source_file:
                source_keys.add(
                    canonical_source_document_key(source_file, source_record)
                )

            if build_ngrams:
                ngram_hashes.update(unique_word_ngram_hashes(normalized, ngram_size))

    if documents == 0:
        raise ValueError("training corpus contains no documents")

    return TrainingReference(
        documents=documents,
        utf8_bytes=utf8_bytes,
        source_document_keys=frozenset(source_keys),
        text_sha256=frozenset(text_hashes),
        ngram_hashes=frozenset(ngram_hashes),
    )


def training_ngram_overlap_ratio(
    text: str,
    *,
    training_ngrams: frozenset[int],
    ngram_size: int,
    min_ngrams: int,
) -> float | None:
    # Preserve repeated candidate shingles in the denominator. This catches
    # copied/repeated excerpts that may contain only a small number of unique
    # shingles but are still overwhelmingly derived from training text.
    candidate = word_ngram_hashes(text, ngram_size)
    if len(candidate) < min_ngrams:
        return None

    overlap = sum(1 for item in candidate if item in training_ngrams)
    return overlap / len(candidate)


def decontaminate_candidates(
    candidates: dict[str, list[base.CandidateDocument]],
    *,
    training: TrainingReference,
    ngram_size: int,
    max_ngram_overlap: float,
    min_ngrams: int,
    use_ngram_check: bool,
    stats: EvalBuildStats,
) -> tuple[
    dict[str, list[base.CandidateDocument]],
    list[ContaminationRejection],
]:
    clean: dict[str, list[base.CandidateDocument]] = defaultdict(list)
    rejected: list[ContaminationRejection] = []

    for category in sorted(candidates):
        for document in candidates[category]:
            stats.candidates_before_decontamination += 1
            stats.candidate_bytes_before_decontamination += document.utf8_bytes

            source_key = canonical_source_document_key(
                document.source_file,
                document.source_record,
            )

            if source_key in training.source_document_keys:
                stats.rejected_same_training_source_document += 1
                rejected.append(
                    ContaminationRejection(
                        category=document.category,
                        source_file=document.source_file,
                        source_record=document.source_record,
                        source_chunk=document.source_chunk,
                        reason="same_training_source_document",
                        utf8_bytes=document.utf8_bytes,
                    )
                )
                continue

            if document.sha256 in training.text_sha256:
                stats.rejected_exact_training_text += 1
                rejected.append(
                    ContaminationRejection(
                        category=document.category,
                        source_file=document.source_file,
                        source_record=document.source_record,
                        source_chunk=document.source_chunk,
                        reason="exact_training_text",
                        utf8_bytes=document.utf8_bytes,
                    )
                )
                continue

            overlap_ratio: float | None = None
            if use_ngram_check:
                overlap_ratio = training_ngram_overlap_ratio(
                    document.text,
                    training_ngrams=training.ngram_hashes,
                    ngram_size=ngram_size,
                    min_ngrams=min_ngrams,
                )
                if overlap_ratio is not None and overlap_ratio >= max_ngram_overlap:
                    stats.rejected_training_ngram_overlap += 1
                    rejected.append(
                        ContaminationRejection(
                            category=document.category,
                            source_file=document.source_file,
                            source_record=document.source_record,
                            source_chunk=document.source_chunk,
                            reason="training_ngram_overlap",
                            utf8_bytes=document.utf8_bytes,
                            training_ngram_overlap=overlap_ratio,
                        )
                    )
                    continue

            clean[category].append(document)

    return dict(clean), rejected


def _source_seed(seed: int, source_key: tuple[str, int | None]) -> int:
    payload = f"{seed}:{source_key[0]}:{source_key[1]}".encode("utf-8")
    digest = hashlib.sha256(payload).digest()
    return int.from_bytes(digest[:8], "big")


def cap_source_document_contribution(
    candidates: dict[str, list[base.CandidateDocument]],
    *,
    max_source_document_bytes: int,
    seed: int,
    stats: EvalBuildStats,
) -> dict[str, list[base.CandidateDocument]]:
    """Limit bytes contributed by one original source document before sampling."""
    result: dict[str, list[base.CandidateDocument]] = defaultdict(list)

    for category in sorted(candidates):
        grouped: dict[
            tuple[str, int | None],
            list[base.CandidateDocument],
        ] = defaultdict(list)

        for document in candidates[category]:
            key = canonical_source_document_key(
                document.source_file,
                document.source_record,
            )
            grouped[key].append(document)

        for source_key in sorted(grouped):
            pool = list(grouped[source_key])
            random.Random(_source_seed(seed, source_key)).shuffle(pool)

            kept_bytes = 0
            kept_any = False
            for document in pool:
                if (
                    kept_any
                    and kept_bytes + document.utf8_bytes > max_source_document_bytes
                ):
                    stats.rejected_source_document_cap += 1
                    continue

                # Always permit the first candidate from a source document even if
                # it individually exceeds the cap (it still obeys --max-chars).
                result[category].append(document)
                kept_bytes += document.utf8_bytes
                kept_any = True

    return dict(result)


def ensure_output_directory(path: Path, *, overwrite: bool) -> Path:
    output = path.expanduser().resolve()
    if output.exists() and not output.is_dir():
        raise ValueError(f"output path exists and is not a directory: {output}")

    output.mkdir(parents=True, exist_ok=True)
    managed = {
        DEFAULT_OUTPUT_FILENAME,
        "manifest.json",
        "build_report.json",
    }
    existing = [output / name for name in managed if (output / name).exists()]

    if existing and not overwrite:
        names = ", ".join(item.name for item in existing)
        raise FileExistsError(
            f"output already contains generated files ({names}); "
            "use --overwrite to replace them"
        )

    return output


def write_eval_jsonl(
    path: Path,
    documents: Sequence[base.CandidateDocument],
) -> str:
    digest = hashlib.sha256()

    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for document in documents:
            record = {
                "id": document.document_id,
                "category": document.category,
                "source_file": document.source_file,
                "source_record": document.source_record,
                "source_chunk": document.source_chunk,
                "source_sha256": document.sha256,
                "characters": document.characters,
                "utf8_bytes": document.utf8_bytes,
                "text": document.text,
            }
            serialized = json.dumps(
                record,
                ensure_ascii=False,
                separators=(",", ":"),
            )
            line = serialized + "\n"
            handle.write(line)
            digest.update(line.encode("utf-8"))

    return digest.hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def category_distribution(
    documents: Sequence[base.CandidateDocument],
) -> dict[str, dict[str, float | int]]:
    by_category: dict[str, list[base.CandidateDocument]] = defaultdict(list)
    for document in documents:
        by_category[document.category].append(document)

    total_documents = len(documents)
    total_bytes = sum(document.utf8_bytes for document in documents)

    result: dict[str, dict[str, float | int]] = {}
    for category in sorted(by_category):
        docs = by_category[category]
        bytes_ = sum(document.utf8_bytes for document in docs)
        result[category] = {
            "documents": len(docs),
            "utf8_bytes": bytes_,
            "document_fraction": len(docs) / total_documents if total_documents else 0.0,
            "byte_fraction": bytes_ / total_bytes if total_bytes else 0.0,
        }
    return result


def eligible_distribution(
    candidates: dict[str, list[base.CandidateDocument]],
) -> dict[str, dict[str, int]]:
    return {
        category: {
            "documents": len(documents),
            "utf8_bytes": sum(document.utf8_bytes for document in documents),
        }
        for category, documents in sorted(candidates.items())
    }


